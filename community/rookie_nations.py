def pick(field, rng):
    country, _w, pool = rng.choices(field, [x[1] for x in field])[0]
    return country, pool


def name(pool: str, rng) -> str:
    a, b, sep = POOLS[pool]
    return f'{rng.choice(a)}{sep}{rng.choice(b)}'


def family(pool: str, full: str) -> str:
    """성 — 일본은 앞 단어, 영어·스페인어권은 뒤 단어, 대만은 붙여 쓴 앞부분(차이·랴오처럼 두 글자 성도 있다)."""
    if pool == 'tw':
        return max((s for s in POOLS['tw'][0] if full.startswith(s)), key=len, default=full[:1])
    parts = full.split()
    return parts[0] if pool == 'jp' else parts[-1]


def plan(league: str, talents: list, gens: list, seed: str) -> dict:
    """로스터 자리 → (나라, 이름 조각, 꼬리표). 자국 선수 자리는 빠진다.

    talents·gens 는 로스터 순서(0~11 타자, 12~16 선발, 17~19 불펜)의 재능·세대(은퇴 뒤 새 선수면 1씩 는다).
    정원제 리그는 같은 역할에서 재능이 높은 자리부터 외국인으로 채운다(에이스·중심 타자로 데려오니까).
    어느 자리가 외국인인지는 구단마다 고정이고, 그 자리에 새 선수가 들어오면(세대가 바뀌면) 나라도 다시 뽑는다.
    """
    rng = random.Random('nation:' + seed)
    slots = {}                                  # 자리 → (나라 무게, 꼬리표)
    best = lambda idx: sorted(idx, key=lambda i: -talents[i])
    if league in QUOTA:
        shapes, field, tag = QUOTA[league]
        n_pit, n_bat, _ = rng.choices(shapes, [s[2] for s in shapes])[0]
        sp_n = min(n_pit, 2) if league == 'npb1' else n_pit      # NPB 외국인 투수 셋째는 마무리·셋업
        if league == 'cpbl' and n_pit == 3 and rng.random() < .2:
            sp_n = 2                                              # CPBL 도 가끔 외국인 마무리
        for i in best(SP)[:sp_n] + best(RP)[:n_pit - sp_n] + best(FOREIGN_BAT)[:n_bat]:
            slots[i] = (field, tag)
        if league in ASIA_QUOTA:
            field, p_pitch = ASIA_QUOTA[league]
            group = list(SP) + list(RP) if rng.random() < p_pitch else FOREIGN_BAT
            slots[next(i for i in best(group) if i not in slots)] = (field, '아시아쿼터')
    elif league in LOOSE:
        n, field = LOOSE[league]
        for i in rng.sample(range(len(talents)), n):
            slots[i] = (field, '외국인')
    elif league in INTL_RATE:
        field = MLB_INTL if league == 'mlb' else MILB_INTL
        for i in range(len(talents)):
            if random.Random(f'nation:{seed}:{i}:{gens[i]}').random() < INTL_RATE[league]:   # 새 선수는 국적도 새로
                slots[i] = (field, '')
    out = {}
    for i, (field, tag) in slots.items():
        out[i] = (*pick(field, random.Random(f'country:{seed}:{i}:{gens[i]}')), tag)
    return out
