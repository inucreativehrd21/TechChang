def source_block(key: str, no: int) -> str:
    """회차의 실제 코드 발췌 블록(프롬프트용). 파일이나 기준 줄을 못 찾으면 그 항목은 건너뛴다."""
    import re
    from pathlib import Path
    from django.conf import settings

    parts = []
    for rel, anchor, n in SOURCES.get(key, {}).get(no, []):
        path = Path(settings.BASE_DIR) / rel
        try:
            lines = path.read_text(encoding='utf-8').splitlines()
        except OSError:
            continue
        start = next((i for i, line in enumerate(lines) if re.search(anchor, line)), None)
        if start is None:
            continue
        lang = {'.py': 'python', '.html': 'html'}.get(path.suffix, '')
        if n is None:     # 그 함수·클래스 끝까지 — 3편 발췌가 30줄에서 잘려 마지막 return 을 집필자가 지어냈다
            end = next((i for i in range(start + 1, len(lines))
                        if re.match(r'(def |class |@)', lines[i]) and not lines[i - 1].startswith('@')), len(lines))
            n = end - start
        parts.append(f'# {rel}\n```{lang}\n' + '\n'.join(lines[start:start + n]).rstrip() + '\n```')
    if not parts:
        return ''
    return ('\n[테크창 실제 코드 발췌 — 예제는 이 코드를 바탕으로 쓰고, 파일 경로를 밝혀 주세요]\n'
            + '\n\n'.join(parts) + '\n')

