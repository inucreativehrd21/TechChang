def next_publish_at(key: str, last_published=None, now=None):
    """다음 회차 공개 예정 시각(지역 시간). 일정이 없으면 None."""
    sch = SCHEDULE.get(key)
    if not sch:
        return None
    now = now or timezone.localtime()
    earliest = now
    if last_published is not None:
        earliest = max(now, timezone.localtime(last_published) + timedelta(days=MIN_GAP_DAYS))
    day = earliest.date()
    for _ in range(60):
        if day.weekday() == sch['weekday'] and day.isocalendar()[1] % 2 == sch['week_parity']:
            at = timezone.make_aware(datetime.combine(day, time(sch['hour'])))
            if at >= earliest:
                return at
        day += timedelta(days=1)
    return None


def too_soon(last_published, now=None) -> bool:
    """직전 회차 발행 후 MIN_GAP_DAYS 가 안 지났으면 True (cron 이 건너뛴다)."""
    if last_published is None:
        return False
    now = now or timezone.now()
    return now - last_published < timedelta(days=MIN_GAP_DAYS)
