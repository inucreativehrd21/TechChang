BY_KEY = {s['key']: s for s in STORIES}


def words(c) -> dict:
    """이야기 글자 자리 — 투수·타자, 지금 리그."""
    from . import rookie_world as W
    pitcher = c.role == 'pitcher'
    return {'sound': '미트 소리' if pitcher else '타구 소리', 'tool': '공을' if pitcher else '방망이를',
            'spot': '마운드' if pitcher else '타석', 'years': (c.flags or {}).get('pro_years') or '여러',
            'league': W.short(c.league) if c.league else '퓨처스'}


def pool(c) -> list:
    from . import rookie_world as W
    minor = c.league not in W.TOP_LEAGUES
    return [s for s in STORIES if minor or not s.get('minor')]


def pick(c, seed: str) -> str:
    """제안마다 이야기 하나 — 같은 씨앗이면 같은 이야기."""
    import hashlib
    choices = pool(c)
    return choices[int(hashlib.sha256(f'bloom-story:{seed}'.encode()).hexdigest()[:8], 16) % len(choices)]['key']


def render(c, key: str) -> dict:
    """화면용 — 글자 자리를 채운 이야기. 모르는 key(예전 저장)면 처음 이야기."""
    s = BY_KEY.get(key) or STORIES[0]
    w = words(c)
    fill = lambda lines: [line.format(**w) for line in lines]          # noqa: E731
    return dict(key=s['key'], title=s['title'], intro=fill(s['intro']), try_label=s['try_label'].format(**w),
                ok=fill(s['ok']), fail=fill(s['fail']))
