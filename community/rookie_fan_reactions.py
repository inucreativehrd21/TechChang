def _number(value):
    return int(hashlib.sha256(str(value).encode()).hexdigest()[:12], 16)


def _pick(topic, identity, turn, slot):
    pool = BANK[topic]
    stride = next(n for n in (5, 7, 11, 13) if math.gcd(n, len(pool)) == 1)
    base = _number(f'{identity}:{topic}:{slot}')
    index = (base + turn * stride) % len(pool)
    tail = TAILS[(base // len(pool) + turn * 7) % len(TAILS)]
    return pool[index] + (' · ' + tail if tail else ''), f'{topic}:{index}'


def season(c, s):
    t = s.totals or {}
    b, p = L.batting(t), L.pitching(t)
    fan = 'champion' if s.champion else 'bottom' if s.team_of and s.team_rank == s.team_of else 'ordinary'
    if c.role == 'pitcher':
        record = 'no_play' if not t.get('outs') else 'pitcher_hot' if p['era'] <= 3 else 'pitcher_cold' if p['era'] >= 5 else 'pitcher_mid'
    else:
        record = 'no_play' if not t.get('pa') else 'slugger' if t.get('hr', 0) >= 30 else 'speed' if t.get('sb', 0) >= 30 else 'batter_hot' if b['ops'] >= .850 else 'batter_cold' if b['ops'] < .650 else 'batter_mid'
    outlook = 'moved' if len(s.splits or []) > 1 else 'veteran' if s.age >= 34 else 'prospect' if not W.is_pro(s.league) else 'pro_next'
    values = dict(name=c.name, team=W.club_short(s.league, s.club), age=s.age, ops=f"{b['ops']:.3f}", era=f"{p['era']:.2f}",
                  hr=t.get('hr', 0), sb=t.get('sb', 0), so=t.get('so', 0), bb=t.get('bb', 0))
    polite = [pool[(_number(f'{c.pk}:polite:{i}') + s.year * 5) % len(pool)].format(**values)
              for i, pool in enumerate(POLITE)]
    if record != 'no_play':
        polite[1] = ((f"ERA {values['era']}, 탈삼진 {values['so']}개, 볼넷 {values['bb']}개예요. " if c.role == 'pitcher'
                      else f"OPS {values['ops']}, {values['hr']}홈런이에요. ") + polite[1])
    else:
        polite[1] = '출전 기록이 적어 숫자만으로 기량을 단정하기 어려워요. ' + polite[1]
    comments = []
    for i, topic in enumerate((fan, record, outlook)):
        style = PATTERN[((s.year - 1) * 3 + i) % 10]
        text, key = _pick(topic, f'{c.pk}:{c.role}', s.year, i)
        rendered = text.format(**values)
        if i == 1 and record != 'no_play':
            if c.role == 'batter' and 'OPS' not in rendered:
                rendered += f" · OPS {values['ops']}"
            elif c.role == 'pitcher' and 'ERA' not in rendered:
                rendered += f" · ERA {values['era']}"
        comments.append(dict(style=style, key=key, topic=topic,
            name=('직관하는 팬', '기록 보는 팬', '다음 시즌도')[i] if style == 'standard' else
                 ('ㅇㅇ', '야구보는중', '기록실상주', '직관갈사람', '타순메모장', '불펜대기중')[(_number(c.pk) + s.year + i) % 6],
            text=polite[i] if style == 'standard' else rendered))
    return comments


