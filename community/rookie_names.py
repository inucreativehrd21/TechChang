"""야구선수 키우기(라이트·정식 판) 선수 이름 — 정치인·역대 대통령 이름은 쓸 수 없다(2026-10-19 사용자 요청, 1.0 출시).

공백·기호를 빼고 비교한다. 세 글자 이상 이름은 들어 있기만 해도 막고(‘윤석열짱’), 두 글자 이름은 똑같을 때만 막는다
(‘조국’이 들어간 다른 말까지 막지 않게). 목록은 대한민국 역대 대통령과 대표적인 정치인·국내외 정치 지도자다 — 더 막을 이름은
여기 덧붙이면 된다.
"""
import re

PRESIDENTS = ('이승만', '윤보선', '박정희', '최규하', '전두환', '노태우', '김영삼', '김대중', '노무현', '이명박', '박근혜',
              '문재인', '윤석열', '이재명')
POLITICIANS = ('김건희', '김정숙', '김종필', '이회창', '정동영', '손학규', '김종인', '이해찬', '박지원', '정세균', '이낙연',
               '김부겸', '한덕수', '황교안', '추미애', '송영길', '조국', '유시민', '심상정', '안철수', '유승민', '이준석', '한동훈',
               '홍준표', '오세훈', '원희룡', '김문수', '나경원', '권성동', '장동혁', '정청래', '우원식', '김동연', '박원순')
# 흔한 이름과 겹치는 정치인(김민석·이상민 등)은 넣지 않았다 — 같은 이름의 평범한 선수를 막지 않게
LEADERS = ('김일성', '김정일', '김정은', '김여정', '트럼프', '바이든', '오바마', '푸틴', '시진핑', '마오쩌둥', '모택동', '히틀러',
           '스탈린', '무솔리니', '젤렌스키', '네타냐후', '기시다', '이시바', '아베', '다카이치', 'trump', 'biden', 'obama',
           'putin', 'xijinping', 'hitler', 'stalin', 'kimjongun')
BLOCKED = tuple(n.lower() for n in PRESIDENTS + POLITICIANS + LEADERS)
MESSAGE = '정치인·역대 대통령 이름은 선수 이름으로 쓸 수 없어요. 다른 이름을 지어 주세요.'


def _norm(name: str) -> str:
    return re.sub(r'[\s\W_]+', '', (name or '')).lower()


def blocked(name: str) -> bool:
    n = _norm(name)
    if not n:
        return False
    return any((b in n) if len(b) >= 3 else (b == n) for b in BLOCKED)
